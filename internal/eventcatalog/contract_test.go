var updateEventSchemas = flag.Bool("update-event-schemas", false, "rewrite the published event contract from the payload types")

// contractFile is the published event contract for reading and diffing; the SDK generates its event types from it.
const contractFile = "schemas.json"

// publishedFile holds the same schemas compact, as the server publishes them, so a boot parses nothing.
const publishedFile = "schemas_gen.go"

// TestSchemas_MatchThePublishedContract fails on a payload change that would break a consumer of the published catalog
// (ADR 0044): a field removed or renamed, a type widened, an enum value dropped, a field no longer always sent. It
// also fails when the file lags an additive change, the way sqlc diff does; make event-schemas brings it level.
func TestSchemas_MatchThePublishedContract(t *testing.T) {
	generated, err := generateSchemas()
	require.NoError(t, err)
	onFile := readContract(t)

	require.Empty(t, breaking(decode(t, onFile), decode(t, generated)),
		"the published event contract only grows; ship a new field or topic beside the old one instead")
	if *updateEventSchemas {
		writeContract(t, generated)
		return
	}
	assert.Empty(t, differing(onFile, generated), "stale; regenerate with make event-schemas")
	assert.Empty(t, differing(Schemas(), generated), "stale; regenerate with make event-schemas")
}

func differing(a, b map[string]string) []string {
	var names []string
	for _, name := range slices.Sorted(maps.Keys(a)) {
		if a[name] != b[name] {
			names = append(names, name)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(b)) {
		if _, ok := a[name]; !ok {
			names = append(names, name)
		}
	}
	return names
}

func readContract(t *testing.T) map[string]string {
	t.Helper()
	raw, err := os.ReadFile(contractFile)
	require.NoError(t, err)
	var schemas map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(raw, &schemas))
	out := make(map[string]string, len(schemas))
	for name, schema := range schemas {
		var text bytes.Buffer
		require.NoError(t, json.Compact(&text, schema))
		out[name] = text.String()
	}
	return out
}

func writeContract(t *testing.T, schemas map[string]string) {
	t.Helper()
	raws := make(map[string]json.RawMessage, len(schemas))
	for name, text := range schemas {
		raws[name] = json.RawMessage(text)
	}
	out, err := json.MarshalIndent(raws, "", "  ")
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(contractFile, append(out, '\n'), 0o644))

	var src bytes.Buffer
	src.WriteString("// Code generated by make event-schemas. DO NOT EDIT.\n\npackage eventcatalog\n\nvar published = map[string]string{\n")
	for _, name := range slices.Sorted(maps.Keys(schemas)) {
		fmt.Fprintf(&src, "\t%q: %q,\n", name, schemas[name])
	}
	src.WriteString("}\n")
	formatted, err := format.Source(src.Bytes())
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(publishedFile, formatted, 0o644))
}

