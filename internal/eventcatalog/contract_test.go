// contractOf generates payload's schema as the topic t.order, decoded the way the contract file holds it.
func contractOf(t *testing.T, payload any) map[string]any {
	t.Helper()
	generated, err := generate([]eventbus.Topic{{Name: "t.order", Payload: payload}})
	require.NoError(t, err)
	texts := map[string]string{}
	for name, s := range generated {
		text, err := json.Marshal(s)
		require.NoError(t, err)
		texts[name] = string(text)
	}
	return decode(t, texts)
}

func decode(t *testing.T, texts map[string]string) map[string]any {
	t.Helper()
	out := make(map[string]any, len(texts))
	for name, text := range texts {
		var s any
		require.NoError(t, json.Unmarshal([]byte(text), &s), name)
		out[name] = s
	}
	return out
}

// breaking lists what a consumer of the old contract would lose in the new one: a topic, a field, a type, an enum
// value, or a field it could count on being sent.
func breaking(old, current map[string]any) []string {
	var problems []string
	for _, name := range slices.Sorted(maps.Keys(old)) {
		next, ok := current[name]
		if !ok {
			problems = append(problems, name+": topic removed")
			continue
		}
		problems = append(problems, breakingAt(name, old[name], next)...)
	}
	return problems
}

func breakingAt(path string, oldNode, newNode any) []string {
	o, _ := oldNode.(map[string]any)
	n, _ := newNode.(map[string]any)
	var problems []string
	if a, b := types(o), types(n); !narrows(a, b) {
		problems = append(problems, fmt.Sprintf("%s: type %s became %s", path, typeName(a), typeName(b)))
	}
	if oldEnum, ok := o["enum"].([]any); ok {
		newEnum, _ := n["enum"].([]any)
		for _, v := range oldEnum {
			if !slices.Contains(newEnum, v) {
				problems = append(problems, fmt.Sprintf("%s: enum value %v removed", path, v))
			}
		}
	}
	newRequired, _ := n["required"].([]any)
	if oldRequired, ok := o["required"].([]any); ok {
		for _, name := range oldRequired {
			if !slices.Contains(newRequired, name) {
				problems = append(problems, fmt.Sprintf("%s: %v no longer required", path, name))
			}
		}
	}
	oldProps, _ := o["properties"].(map[string]any)
	newProps, _ := n["properties"].(map[string]any)
	for _, name := range slices.Sorted(maps.Keys(oldProps)) {
		next, ok := newProps[name]
		if !ok {
			problems = append(problems, fmt.Sprintf("%s/%s: removed", path, name))
			continue
		}
		problems = append(problems, breakingAt(path+"/"+name, oldProps[name], next)...)
	}
	for _, key := range []string{"items", "additionalProperties"} {
		if sub, ok := o[key]; ok {
			problems = append(problems, breakingAt(path+"/"+key, sub, n[key])...)
		}
	}
	return problems
}

func types(s map[string]any) []string {
	switch t := s["type"].(type) {
	case string:
		return []string{t}
	case []any:
		out := make([]string, 0, len(t))
		for _, v := range t {
			out = append(out, fmt.Sprint(v))
		}
		slices.Sort(out)
		return out
	}
	return nil
}

// narrows reports whether a field typed next can only carry what one typed was could: dropping null is safe for a
// consumer, a new type or an untyped field is not.
func narrows(was, next []string) bool {
	if len(was) == 0 {
		return true
	}
	return len(next) > 0 && !slices.ContainsFunc(next, func(t string) bool { return !slices.Contains(was, t) })
}

func typeName(ts []string) string {
	if len(ts) == 0 {
		return "any"
	}
	return strings.Join(ts, "|")
}

