package permissions

import (
	"flag"
	"os"
	"strconv"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

var updatePermissionCatalog = flag.Bool("update-permission-catalog", false, "rewrite the clients' copy of the permission catalog")

// permissionActionsFile is the clients' typed copy of the catalog, imported by the web and the phone.
const permissionActionsFile = "../../../client-core/permissionActions.ts"

// renderClientCatalog writes every grid action, its label and the instance-scoped ones as TypeScript, in display order.
func renderClientCatalog() string {
	var b strings.Builder
	b.WriteString("// Generated by `make permission-catalog` from internal/platform/permissions; do not edit.\n\n")
	b.WriteString("export const PERMISSION_ACTIONS = [\n")
	for _, info := range Catalog() {
		b.WriteString("  " + strconv.Quote(string(info.Value)) + ",\n")
	}
	b.WriteString("] as const;\n\nexport type PermissionAction = (typeof PERMISSION_ACTIONS)[number];\n\n")
	b.WriteString("export const PERMISSION_LABELS: Record<PermissionAction, string> = {\n")
	for _, info := range Catalog() {
		b.WriteString("  " + strconv.Quote(string(info.Value)) + ": " + strconv.Quote(info.Label) + ",\n")
	}
	b.WriteString("};\n\n// The actions of instance domains, held through the auth /me's instance_permissions, not a workspace's /me.\n")
	b.WriteString("export const INSTANCE_PERMISSION_ACTIONS: readonly PermissionAction[] = [\n")
	for _, info := range Catalog() {
		if info.Area == AreaInstance {
			b.WriteString("  " + strconv.Quote(string(info.Value)) + ",\n")
		}
	}
	b.WriteString("];\n")
	return b.String()
}

// TestPermissionActionsFile_MatchesTheCatalog fails when the clients' typed copy of the catalog is stale, the way sqlc diff does.
func TestPermissionActionsFile_MatchesTheCatalog(t *testing.T) {
	want := renderClientCatalog()
	if *updatePermissionCatalog {
		require.NoError(t, os.WriteFile(permissionActionsFile, []byte(want), 0o644))
	}
	got, err := os.ReadFile(permissionActionsFile)
	require.NoError(t, err)
	assert.Equal(t, want, string(got), "stale; regenerate with make permission-catalog")
}
